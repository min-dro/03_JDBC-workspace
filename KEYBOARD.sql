DROP TABLE KEYBOARD;

CREATE TABLE KEYBOARD (
    KEYBOARD_NO NUMBER PRIMARY KEY,
    BRAND VARCHAR2(30) NOT NULL,
    MODEL_NAME VARCHAR2(50) NOT NULL UNIQUE,
    KEY_COUNT NUMBER, 
    SWITCH_TYPE VARCHAR2(30),
    CONNECTION VARCHAR2(20) CHECK(CONNECTION IN ('유선', '무선', '유무선')),
    PRICE NUMBER,
    RGB CHAR(1) DEFAULT 'N' CHECK(RGB IN ('N', 'Y'))
);

